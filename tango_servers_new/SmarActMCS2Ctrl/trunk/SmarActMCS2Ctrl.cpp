/**
 *	Write attribute ImageWriteDynAttr related method
 *	Description: Data for trajectory movement, must be organized like this:
 *               
 *               axis_X position axis_Y position axis_Z position ...
 *               axis_X position axis_Y position axis_Z position ...
 *               axis_X position axis_Y position axis_Z position ...
 *               axis_X position axis_Y position axis_Z position ...
 *               ...
 *
 *	Data type:	Tango::DevDouble
 *	Attr type:	Image max = 30 x 100000000
 */
//--------------------------------------------------------
void SmarActMCS2Ctrl::write_ImageWriteDynAttr(Tango::WAttribute &attr)
{
	DEBUG_STREAM << "SmarActMCS2Ctrl::write_ImageWriteDynAttr(Tango::WAttribute &attr) entering... " << endl;
	//	Retrieve number of write values
	int	w_length = attr.get_write_value_length();

	//	Retrieve pointer on write values (Do not delete !)
	const Tango::DevDouble	*w_val;
	attr.get_write_value(w_val);
	/*----- PROTECTED REGION ID(SmarActMCS2Ctrl::write_ImageWriteDynAttr) ENABLED START -----*/
	if(attr.get_name() == "TrajectoryData")
	{
		if(trajectoryActive())
		{
			Tango::Except::throw_exception(
		    "Write error",
	        "Trajectoy running, no data write possible",	
			"write_ImageWriteDynAttr",
			Tango::WARN);
		}
		// find number of participating axes
		int firstaxis = -1;
		int axis;
		for(int i = 0, j = 0; i < w_length; i += 2, j++)
		{
			axis = w_val[i];
			positioners[axis]->trajectory(true);
			if(firstaxis == axis)
			{
				numAxesInTrajectory = j;
				break;
			}
			if(i == 0)
			{
				firstaxis = w_val[i];
			}
		}
		for(int i = 0; i < w_length; i += numAxesInTrajectory * 2)
		{
			StreamTargetPtrVector trajPosLine = StreamTargetPtrVector(new vector<StreamTargetPtr>);
 			for(int j = 0; j < numAxesInTrajectory * 2; j += 2)
 			{
 				StreamTargetPtr stpr = StreamTargetPtr(new StreamTarget(w_val[j + i], (int64_t) (w_val[j + i + 1] * positioners[w_val[j + i]]->conversion())));
 				trajPosLine->push_back(stpr);
 			}
 			trajectoryTargetQueue.push_back(trajPosLine);
 		}
	}
	/*----- PROTECTED REGION END -----*/	//	SmarActMCS2Ctrl::write_ImageWriteDynAttr
}
