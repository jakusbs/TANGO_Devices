void SmarActMCS2Ctrl::updateEventState(int8_t idx, uint32_t evType, int32_t evState)
{
    positioners[idx]->eventType(evType);
    positioners[idx]->eventState(evState);
    if(evType >= SA_CTL_EVENT_MOVEMENT_FINISHED && evType <= SA_CTL_EVENT_HOLDING_ABORTED)
    {
		eventMutex.lock();
        attr_EventInfo_read[0] = Tango::DevULong(idx);
        attr_EventInfo_read[1] = Tango::DevULong(evType);
        attr_EventInfo_read[2] = Tango::DevULong(evState);
		eventMutex.unlock();
        push_change_event("EventInfo", attr_EventInfo_read, 3);
    }
	
}

