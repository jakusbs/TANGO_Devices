//	Additional Methods
void SmarActMCS2Ctrl::makeLocator(string& _hostname, string& _usbid, string& _connecttype, stringstream& _locator, Tango::DevLong portNumber)
{
    _locator.str("");
    if(_connecttype == "net")
    {
	    struct addrinfo *result;
	    char addr[100];
	    int errcode;
	    void *ptr;
	    if((errcode = getaddrinfo(_hostname.c_str(), NULL, NULL, &result)) != 0)
	    {
		    set_state(Tango::FAULT);
		    set_status(gai_strerror(errcode));
		    return;
	    }
	    for(struct addrinfo *res = result; res != NULL; res = res->ai_next)
	    {
		    if( !(inet_ntop(res->ai_family, res->ai_addr->sa_data, addr, 100)) )
		    {
			    set_state(Tango::FAULT);
			    set_status(strerror(errno));
			    return;
		    }		
		    switch(res->ai_family)
       		{
       		    case AF_INET:
       				ptr = &((struct sockaddr_in *) res->ai_addr)->sin_addr;
       			break;
       			case AF_INET6:
       				ptr = &((struct sockaddr_in6 *) res->ai_addr)->sin6_addr;
       			break;
		    }
		    if( !(inet_ntop (res->ai_family, ptr, addr, 100)))
		    {
			    set_state(Tango::FAULT);
			    set_status(strerror(errno));
			    return;
		    }

	    }
        _locator << "network:" << addr;
        if(portNumber && _connecttype == "net")
        {
            _locator << ':' << portNumber;
        }
    }
    else if(connectType == "usb")
    {
         _locator << "usb:id:" << _usbid;
    }
    if(ttydebug)
    {
        cerr << "Locator: " << _locator.str() << endl;
    }
	set_state(Tango::ON);
	set_status("The device is in ON state");
}

void SmarActMCS2Ctrl::getPositionerInfo()
{
    getProperty(0, SA_CTL_PKEY_NUMBER_OF_CHANNELS, &nchannels);
    int32_t value;
    for(int8_t i = 0; i < nchannels; i++)
    {
        Positioner* p = new Positioner;
        getProperty(i, SA_CTL_PKEY_AMPLIFIER_ENABLED, &value);
        p->enabled(value);
        getProperty(i, SA_CTL_PKEY_POSITIONER_TYPE, &value);
        p->type(value);
        getProperty(i, SA_CTL_PKEY_POS_BASE_UNIT, &value);
        p->unit(value);
		getProperty(i, SA_CTL_PKEY_SENSOR_POWER_MODE, &value);
		p->powerMode(value);
		p->channel(i);
        positioners.push_back(p);
    }
}

void SmarActMCS2Ctrl::positionersReset()
{
	for(auto it = positioners.begin(); it != positioners.end(); ++it)
	{
		if((*it)->trajectory())
		{
			setProperty((*it)->channel(), SA_CTL_PKEY_AMPLIFIER_ENABLED, (*it)->enabled());
			setProperty((*it)->channel(), SA_CTL_PKEY_SENSOR_POWER_MODE, (*it)->powerMode());
			(*it)->trajectory(false);
		}
	}
}

