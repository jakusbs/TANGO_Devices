/**
 *	Command StartStreaming related method
 *	Description: Start trajectory streaming.
 *               
 *               Make sure attribute TrajectoryData has been written before calling this.
 *               
 *               Smaract commands: SA_CTL_OpenStream/SA_CTL_StreamFrame/SA_CTL_CloseStream
 *
 */
//--------------------------------------------------------
void SmarActMCS2Ctrl::start_streaming()
{
	DEBUG_STREAM << "SmarActMCS2Ctrl::StartStreaming()  - " << device_name << endl;
	/*----- PROTECTED REGION ID(SmarActMCS2Ctrl::start_streaming) ENABLED START -----*/
	
	//	Add your own code
	if(trajectoryActive())
	{
			Tango::Except::throw_exception(
		    "Write error",
	        "Trajectoy already running",	
			"SmarActMCS2Ctrl::start_streaming",
			Tango::WARN);
	}
	if(trajectoryTargetQueue.size() == 0)
	{
		Tango::Except::throw_exception(
		    "Write error",
	        "No trajectory data set",	
			"SmarActMCS2Ctrl::StartStreaming",
			Tango::WARN);
	}
	checkBaseRate();
	int32_t result;
	if(*attr_StreamTriggerMode_read == SA_CTL_STREAM_TRIGGER_MODE_EXTERNAL_SYNC)
	{
		if(*attr_StreamBaseRate_read % *attr_ExternalSyncRate_read != 0)
		{
			Tango::Except::throw_exception(
		    "Write error",
	        "StreamBaseRate is not a whole-number multiple of ExternalSyncRate",	
			"SmarActMCS2Ctrl::StartStreaming",
			Tango::WARN);
		}
		setProperty(0, SA_CTL_PKEY_STREAM_EXT_SYNC_RATE, (int32_t) *attr_ExternalSyncRate_read);
		
	}
	for(auto it = positioners.begin(); it != positioners.end(); ++it)
	{
		if((*it)->trajectory())
		{
			//int64_t pos;
			//getProperty((*it)->channel(), SA_CTL_PKEY_POSITION, &pos);
			//(*it)->position(pos); 
			//setProperty((*it)->channel(), SA_CTL_PKEY_POSITION, (int64_t) 0); // necessary ???
			setProperty((*it)->channel(), SA_CTL_PKEY_AMPLIFIER_ENABLED, (int32_t) SA_CTL_ENABLED);
			setProperty((*it)->channel(), SA_CTL_PKEY_SENSOR_POWER_MODE, (int32_t) SA_CTL_SENSOR_MODE_ENABLED);
		}
	}
	auto firstRow = trajectoryTargetQueue.front();
	for(auto it = firstRow->begin(); it != firstRow->end(); ++it)
	{
		Tango::DevUShort mstate = axis_state((*it)->channel());
		if(!(mstate & SA_CTL_CH_STATE_BIT_IS_REFERENCED))
		{
			positionersReset();
			stringstream tmp;
			tmp << "Can not start streaming, axis " << (int) (*it)->channel() << " is not homed" << endl; 
        	Tango::Except::throw_exception(
		    	"Write error",
				tmp.str(),
				"SmarActMCSCtrl::StartStreaming",
				Tango::WARN);
		}	
		if((result = SA_CTL_Move(handle, (*it)->channel(), (*it)->position(), 0)) != SA_CTL_ERROR_NONE)
    	{
			positionersReset();
        	Tango::Except::throw_exception(
		    	"Write error",
				SA_CTL_GetResultInfo(result),
				"SmarActMCSCtrl::StartStreaming",
				Tango::WARN);
    	}
	}
	trajectoryTerminate = trajectoryStop = false;
	trajectoryStartCondition->signal();
	/*----- PROTECTED REGION END -----*/	//	SmarActMCS2Ctrl::start_streaming
}
