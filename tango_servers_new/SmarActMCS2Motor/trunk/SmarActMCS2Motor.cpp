//	Additional Methods

Tango::DevState  SmarActMCS2Motor::getEventState()
{
    Tango::DevState	retval = Tango::UNKNOWN;
    stringstream attributeName;
    attributeName << "AxisEvent_" << axisNumber;
    Tango::DeviceAttribute eventAttribute;
    vector<Tango::DevULong> eventData;
    eventAttribute = smarctrl->read_attribute(attributeName.str().c_str());
    eventAttribute >> eventData;

    SA_CTL_Event_t event;
    event.idx  = uint32_t(axisNumber);
    event.type = uint32_t(eventData[0]);
    event.i32  = int32_t(eventData[1]);

    // this switch might have to be extended
    switch(event.type)
    {
        case SA_CTL_EVENT_MOVEMENT_FINISHED:
            switch(event.i32)
            {
                case SA_CTL_ERROR_NONE:
                case SA_CTL_ERROR_ABORTED: // movement terminated because Stop was called
                    break;
                default:
                    set_status(SA_CTL_GetEventInfo(&event));
                    retval = Tango::FAULT;
                break;
            }
        break;
        case SA_CTL_EVENT_HOLDING_ABORTED:
		{
			if(event.i32 != SA_CTL_ERROR_ABORTED) // aborted for some special reason
			{
				set_status(SA_CTL_GetEventInfo(&event));
                retval = Tango::FAULT;
			}
		}
		break;
        case SA_CTL_EVENT_OVER_TEMPERATURE:
        case SA_CTL_EVENT_HIGH_VOLTAGE_OVERLOAD:
        case SA_CTL_EVENT_EMERGENCY_STOP_TRIGGERED:
            set_status(SA_CTL_GetEventInfo(&event));
            retval = Tango::FAULT;
        break;
        // don't know yet what to do with these
        case SA_CTL_EVENT_SENSOR_STATE_CHANGED:
        case SA_CTL_EVENT_REFERENCE_FOUND:
        case SA_CTL_EVENT_FOLLOWING_ERR_LIMIT:
        case SA_CTL_EVENT_SM_STATE_CHANGED:
        case SA_CTL_EVENT_ADJUSTMENT_FINISHED:
        case SA_CTL_EVENT_ADJUSTMENT_STATE_CHANGED:
        case SA_CTL_EVENT_ADJUSTMENT_UPDATE:
        case SA_CTL_EVENT_STREAM_FINISHED: 				// handled in controller device
        case SA_CTL_EVENT_STREAM_READY:    				// handled in controller device
        case SA_CTL_EVENT_STREAM_TRIGGERED:				// handled in controller device
        case SA_CTL_EVENT_CMD_GROUP_TRIGGERED:
        case SA_CTL_EVENT_EXT_INPUT_TRIGGERED:
        case SA_CTL_EVENT_REQUEST_READY:
        case SA_CTL_EVENT_CONNECTION_LOST:
        default:
        break;
    }
    return retval;
}

void EventCallback::push_event(Tango::EventData *eventData)
{
    if(eventData->attr_value)
    {
        vector<Tango::DevULong> data;
        *(eventData->attr_value) >> data;
        SA_CTL_Event_t ev;
        ev.idx = data[0];
        ev.type = data[1];
        ev.i32  = data[2];
        if(_ttydebug && ev.idx == _axisnumber)
        {
            cerr << "Got event callback: " << ev.idx << ' ' << ev.type << ' ' << ev.i32 << endl;
        }
    }
}

