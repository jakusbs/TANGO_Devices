/**
 *	Command FindReferenceMark related method
 *	Description: Find reference mark and zero the position there
 *
 */
//--------------------------------------------------------
void Smaract::find_reference_mark()
{
	DEBUG_STREAM << "Smaract::FindReferenceMark()  - " << device_name << endl;
	/*----- PROTECTED REGION ID(Smaract::find_reference_mark) ENABLED START -----*/
	
    // only move if not in FAULT or UNKNOWN state
	if ((get_state() != Tango::FAULT) && (get_state() != Tango::UNKNOWN)) {

        INFO_STREAM << "Smaract::FindReferenceMark()  - moving to reference mark " << endl;
        // set status to moving, changing back status is done in always_executed_hook 
        set_state(Tango::MOVING);
        set_status("Moving to reference mark");

        for (SA_INDEX channel=0; channel<3; channel++) {
            channelActive[channel] = true;
            SmaractResult = SA_FindReferenceMark_S(SmaractHandle,channel,SA_BACKWARD_DIRECTION,holdTime,SA_AUTO_ZERO);
            
            // check for error
            if (SmaractResult != SA_OK) {
                // movement error, shut down
                SA_GetStatusInfo(SmaractResult,&errorText); // errorText points to a descriptive text
                ERROR_STREAM << "Smaract::FindReferenceMark()  - Error@channel " << to_string(channel) << ": " << errorText << endl;
                set_state(Tango::FAULT);
                set_status("Movement error@channel " + to_string(channel) + ": " + string(errorText));
            }
            // wait for completion of reference drive
            // TODO: change to async operation (without blocking wait)
            unsigned int status;
            do {
                SA_GetStatus_S(SmaractHandle,channel,&status);
                usleep (10000); // wait 10 ms
            } while (status != SA_STOPPED_STATUS);

            INFO_STREAM << "Smaract::FindReferenceMark()  - Found mark for channel " << channel << endl;
        }
	}
    
	/*----- PROTECTED REGION END -----*/	//	Smaract::find_reference_mark
}
