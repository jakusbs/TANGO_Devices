Tango::DevDouble Smaract::read_position(SA_INDEX channel)
{	
	// function called from read_position0,1,2 above
	// SmarAct stage uses nm, we use microns
	const Tango::DevDouble nanoPerMicron = 1000.0;
	int positionNano=0;	
	// only read if not in FAULT or UNKNOWN state
	if ((get_state() != Tango::FAULT) && (get_state() != Tango::UNKNOWN)) {

        // read position of stage
        SmaractResult = SA_GetPosition_S(SmaractHandle,channel,&positionNano);
        
        // check if error occurred
        if (SmaractResult != SA_OK) {
            SA_GetStatusInfo(SmaractResult,&errorText); // errorText points to a descriptive text
            set_status("Position reading error@channel " + to_string(channel) + ": " + string(errorText));
            //cout << "Reading position of channel " << to_string(channel) << ", SmaractResult: " << string(errorText) << endl;
            set_state(Tango::UNKNOWN);
            ERROR_STREAM << "Smaract::read_position()  - error@channel " << to_string(channel) << ": " << errorText << endl;
        }
	}
    
	return (Tango::DevDouble)positionNano / nanoPerMicron;
}

void Smaract::write_position(SA_INDEX channel, Tango::DevDouble position)
{
	// function called from write position0,1,2 above
	// holdTime defined as device property
	//unsigned int holdTime = 0;	// in ms, valid range 0-60000. A 0 deactivates this feature, a value of 60000 is infinite


	// SmarAct stage uses nm, we use microns
	const Tango::DevDouble nanoPerMicron = 1000.0;
	int positionNano = (int) (position * nanoPerMicron);

	// only move if not in FAULT or UNKNOWN state (also check state machine!)
	if ((get_state() != Tango::FAULT) && (get_state() != Tango::UNKNOWN)) {

		set_state(Tango::MOVING);
		set_status("Moving Smaract Stage");
		channelActive[channel] = true;

		// initiate absolute movement
		SmaractResult = SA_GotoPositionAbsolute_S(SmaractHandle, channel, positionNano, holdTime);
		
		// check if error
		if (SmaractResult != SA_OK) {
			// movement error, shut down
			SA_GetStatusInfo(SmaractResult,&errorText); // errorText points to a descriptive text
			ERROR_STREAM << "Smaract::write_position()  - error@channel " << to_string(channel) << ": " << errorText << endl;
			set_state(Tango::FAULT);
			set_status("Movement error@channel " + to_string(channel) + ": " + string(errorText));
		}
	}
	
	return;
}


